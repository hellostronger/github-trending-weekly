function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
}

const shortName = (repo) => repo.split('/')[1];

/** 迷你趋势曲线（累计 star），不足 2 个数据点返回 null */
function sparklineSvg(points, w = 104, h = 30) {
  if (!Array.isArray(points) || points.length < 2) return null;
  const vals = points.map((p) => p.stars);
  const min = Math.min(...vals);
  const max = Math.max(...vals);
  const span = max - min || 1;
  const step = w / (points.length - 1);
  const y = (v) => h - 3 - ((v - min) / span) * (h - 6);
  const d = vals
    .map((v, i) => `${i === 0 ? 'M' : 'L'}${(i * step).toFixed(1)},${y(v).toFixed(1)}`)
    .join(' ');
  const NS = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
  svg.setAttribute('class', 'spark');
  const path = document.createElementNS(NS, 'path');
  path.setAttribute('d', d);
  const dot = document.createElementNS(NS, 'circle');
  dot.setAttribute('cx', String((points.length - 1) * step));
  dot.setAttribute('cy', String(y(vals[vals.length - 1]).toFixed(1)));
  dot.setAttribute('r', '2.5');
  const tip = document.createElementNS(NS, 'title');
  tip.textContent = T.sparkTip(
    points[0].date,
    points[points.length - 1].date,
    fmt(vals[0]),
    fmt(vals[vals.length - 1])
  );
  svg.append(path, dot, tip);
  return svg;
}

/* 按当前语言取展示字段（旧数据没有双语字段时优雅回退） */
const displayTitle = (r) => (LANG === 'zh' ? r.title || shortName(r.repo) : shortName(r.repo));
const displayDesc = (r) => (LANG === 'zh' ? r.descriptionZh || r.description : r.description);
const displayCompany = (r) => (LANG === 'en' && r.companyEn ? r.companyEn : r.company || '');

function renderRanking(data, label) {
  $ranking.replaceChildren();
  const repos = data.repos || [];
  if (repos.length === 0) {
    $ranking.append(el('div', 'empty', T.noData));
    return;
  }

  $subtitle.textContent = T.subtitle(data.since, label);
  document.getElementById('table-head').children[4].textContent = T.hWeekly(data.since || CURRENT_SINCE);
  const $h1 = document.querySelector('.hero h1');
  const tp = T.title(data.since || CURRENT_SINCE);
  $h1.replaceChildren(
    document.createTextNode(tp.pre),
    el('span', 'num', String(repos.length)),
    document.createTextNode(tp.post)
  );
  document.title = T.docTitle(data.since || CURRENT_SINCE);

  for (const r of repos) {
    if (r.title) TITLE_BY_REPO[r.repo] = r.title;
    const row = el('a', 'row' + (r.rank <= 3 ? ' top3' : ''));
    row.href = r.url || `https://github.com/${r.repo}`;
    row.target = '_blank';
    row.rel = 'noopener';

    row.append(el('span', 'rank', String(r.rank)));

    const proj = el('span', 'proj');
    proj.append(el('span', 'name', displayTitle(r)));
    const pathline = el('span', 'pathline');
    pathline.append(el('span', 'path', r.repo));
    if (r.language) {
      const pill = el('span', 'lang');
      const dot = el('i');
      dot.style.background = langColor(r.language);
      pill.append(dot, el('span', null, r.language));
      pathline.append(pill);
    }
    proj.append(pathline);
    const desc = displayDesc(r);
    if (desc) proj.append(el('span', 'desc', desc));
    row.append(proj);

    row.append(el('span', 'company', displayCompany(r)));

    const trendCell = el('span', 'trend');
    const spark = sparklineSvg(TRENDS[r.repo]);
    if (spark) trendCell.append(spark);
    row.append(trendCell);

    row.append(el('span', 'delta', `+${fmt(r.weeklyStars)}`));
    row.append(el('span', 'stars', fmt(r.stars)));

    $ranking.append(row);
  }

  const when = new Date(data.generatedAt);
  $updatedAt.textContent = T.footSource(isNaN(when) ? label : when.toLocaleString(LANG === 'zh' ? 'zh-CN' : 'en-US'));
}

async function loadJson(url) {
  const res = await fetch(url, { cache: 'no-store' });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

const latestFile = (since) => (since === 'weekly' ? 'data/latest.json' : `data/latest-${since}.json`);

async function loadLatest(since) {
  if (!LATEST_CACHE[since]) LATEST_CACHE[since] = await loadJson(latestFile(since));
  return LATEST_CACHE[since];
}

async function showLatest() {
  try {
    const data = await loadLatest(CURRENT_SINCE);
    renderRanking(data, data.generatedAt ? data.generatedAt.slice(0, 10) : '');
  } catch (err) {
    $ranking.replaceChildren(el('div', 'empty', T.loadFail(err.message)));
  }
}

/* —— 周榜 / 日榜切换 —— */
function renderTabs() {
  const $tabs = document.getElementById('chart-tabs');
  $tabs.replaceChildren();
  for (const s of ['weekly', 'daily']) {
    const btn = el('button', 'chart-tab' + (s === CURRENT_SINCE ? ' active' : ''));
    btn.type = 'button';
    btn.textContent = s === 'weekly' ? T.tabWeekly : T.tabDaily;
    btn.addEventListener('click', () => {
      if (CURRENT_SINCE === s) return;
      CURRENT_SINCE = s;
      localStorage.setItem('gtw-chart', s);
      renderTabs();
      switchChart();
    });
    $tabs.append(btn);
  }
}

async function switchChart() {
  $ranking.replaceChildren(el('div', 'loading', T.loading));
  await showLatest();
  await renderTrendsSection();
  renderHistory();
}

/* —— 趋势追踪卡片区 —— */
function scrollToRepo(repo) {
  const row = [...document.querySelectorAll('#ranking .row .path')].find(
    (n) => n.textContent === repo
  );
  if (!row) return;
  const target = row.closest('.row');
  target.scrollIntoView({ behavior: 'smooth', block: 'center' });
  target.classList.remove('flash');
  void target.offsetWidth; // 强制 reflow，确保动画可重复触发
  target.classList.add('flash');
}

function renderTrendCard(repo, pts) {
  const card = el('button', 'trend-card');
  card.type = 'button';

  const info = el('span', 'trend-info');
  const title = LANG === 'zh' ? TITLE_BY_REPO[repo] || shortName(repo) : shortName(repo);
  info.append(el('span', 't1', title));
  info.append(el('span', 'r', repo));
  const first = pts[0];
  const last = pts[pts.length - 1];
  const meta = el('span', 'meta');
  meta.append(el('span', null, `${T.daysOnChart(pts.length)} · `));
  meta.append(el('span', null, T.starsRange(fmt(first.stars), fmt(last.stars))));
  info.append(meta);
  card.append(info);

  const spark = sparklineSvg(pts);
  if (spark) card.append(spark);

  card.addEventListener('click', () => scrollToRepo(repo));
  return card;
}

/* 加载趋势时间线数据（需在渲染榜单前调用，迷你曲线才有数据） */
async function loadTrends() {
  try {
    TRENDS = await loadJson('data/trends.json');
  } catch {
    TRENDS = {};
  }
}

/* 渲染趋势追踪卡片区（需在渲染榜单后调用，才能拿到中文标题） */
async function renderTrendsSection() {
  const entries = Object.entries(TRENDS)
    .map(([repo, allPts]) => {
      // 只取当前榜单类型的数据点，同一天去重
      const pts = allPts
        .filter((p) => (p.since || 'weekly') === CURRENT_SINCE)
        .sort((a, b) => a.date.localeCompare(b.date));
      const dedup = [];
      for (const p of pts) {
        if (dedup.length === 0 || dedup[dedup.length - 1].date !== p.date) dedup.push(p);
        else dedup[dedup.length - 1] = p;
      }
      return { repo, pts: dedup };
    })
    .filter((e) => e.pts.length > 0)
    .sort((a, b) => b.pts.length - a.pts.length || b.pts.at(-1).stars - a.pts.at(-1).stars);
  if (entries.length === 0) {
    $trendsSection.hidden = true;
    return;
  }

  $trendsSection.hidden = false;
  const growing = entries.filter((e) => e.pts.length >= 2).length;
  $trendsNote.textContent = T.trendsNote(entries.length, growing);
  $trendsList.replaceChildren();
  for (const e of entries.slice(0, 8)) $trendsList.append(renderTrendCard(e.repo, e.pts));
}

async function loadHistory() {
  try {
    const history = await loadJson('data/history.json');
    if (Array.isArray(history) && history.length > 0) HISTORY = history;
  } catch {
    /* 没有历史归档时静默隐藏 */
  }
}

function renderHistory() {
  if (!Array.isArray(HISTORY) || HISTORY.length === 0) return;
  const items = HISTORY.filter((h) => (h.since || 'weekly') === CURRENT_SINCE);
  if (items.length === 0) {
    $historySection.hidden = true;
    return;
  }
  $historySection.hidden = false;
  $historyList.replaceChildren();
  for (const h of items) {
    const li = document.createElement('li');
    const btn = el('button');
    btn.append(el('span', 'date', h.date));
    const topTitle = LANG === 'zh' ? h.top1Title || h.top1 || '' : shortName(h.top1 || '');
    btn.append(el('span', 't1', T.top1(topTitle)));
    btn.addEventListener('click', () => showArchive(h.date, h.since || 'weekly'));
    li.append(btn);
    $historyList.append(li);
  }
}

/* 标题下的动态状态徽章：让访客一眼了解页面在做什么、数据有多新 */
function renderHeroStats() {
  const $stats = document.getElementById('hero-stats');
  if (!$stats) return;
  const days = Array.isArray(HISTORY) ? new Set(HISTORY.map((h) => h.date)).size : 0;
  const repos = Object.keys(TRENDS).length;
  $stats.replaceChildren(
    el('span', 'chip', T.chipDays(days || 1)),
    el('span', 'chip', T.chipRepos(repos)),
    el('span', 'chip', T.chipSource),
    el('span', 'chip', T.chipAuto)
  );
}

const archiveUrl = (date, since) =>
  since === 'daily' ? `data/archive/daily-${date}.json` : `data/archive/${date}.json`;

async function showArchive(date, since) {
  $ranking.replaceChildren(el('div', 'loading', T.archiveLoading(date)));
  try {
    const data = await loadJson(archiveUrl(date, since || CURRENT_SINCE));
    renderRanking(data, date);
    window.scrollTo({ top: 0, behavior: 'smooth' });
  } catch (err) {
    $ranking.replaceChildren(el('div', 'empty', T.archiveFail(err.message)));
  }
}

/* 初始化固定文案（按当前语言） */
function applyStaticTexts() {
  document.getElementById('intro').textContent = T.intro;
  document.getElementById('foot-hint').textContent = T.footHint;
  const head = document.getElementById('table-head');
  const labels = [T.hRank, T.hProject, T.hCompany, T.hTrend, T.hWeekly(CURRENT_SINCE), T.hTotal];
  [...head.children].forEach((span, i) => (span.textContent = labels[i]));
  document.getElementById('trends-title').textContent = T.trends;
  document.getElementById('history-title').textContent = T.history;
  const btn = document.getElementById('lang-toggle');
  btn.textContent = T.toggle;
  btn.title = LANG === 'zh' ? 'Switch to English' : '切换到中文';
  btn.addEventListener('click', () => {
    localStorage.setItem('gtw-lang', LANG === 'zh' ? 'en' : 'zh');
    location.reload();
  });
}

